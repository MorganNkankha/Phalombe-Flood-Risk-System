"""
build_frontend_data.py: bundles data/geojson/*.geojson into data/phalombe-data.js
so the website also works when index.html is opened directly (no server, no backend).
Usage: python tools/build_frontend_data.py   (run from the project folder)
"""
import json, glob, os, datetime
layers = {}
for path in sorted(glob.glob("data/geojson/*.geojson")):
    name = os.path.splitext(os.path.basename(path))[0]
    with open(path, encoding="utf-8") as f:
        layers[name] = json.load(f)
meta = {"generated": datetime.date.today().isoformat(),
        "hazard_method": "Provisional multi-ring buffer proxy around rivers and Lake Chilwa (not an official flood extent)"}
with open("data/phalombe-data.js", "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/build_frontend_data.py: do not edit by hand */\n")
    f.write("window.PHALOMBE_DATA = ")
    json.dump({"meta": meta, **layers}, f, separators=(",", ":"), ensure_ascii=False)
    f.write(";\n")
print("Wrote data/phalombe-data.js with layers:", ", ".join(layers))
